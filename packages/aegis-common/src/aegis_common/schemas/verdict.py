"""Verdict, score breakdown, and actuator action schemas."""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from aegis_common.schemas.enums import Decision, InvestigationStatus, RiskLevel, Typology


class ScoreBreakdown(BaseModel):
    """Detailed trace of deterministic base score, hard floors, and LLM adjustment."""

    model_config = ConfigDict(frozen=True)

    base: int = Field(ge=0, le=100, description="Deterministic base score from weighted signals")
    floor: int = Field(ge=0, le=100, description="Highest triggered hard-rule risk floor")
    llm_adjustment: int = Field(
        ge=-10, le=10, description="Bounded orchestrator adjustment [-10, +10]"
    )
    signals: dict[str, int] = Field(
        default_factory=dict, description="Points awarded per signal ID"
    )
    rules: list[str] = Field(
        default_factory=list, description="IDs of hard rules triggered (e.g. H1)"
    )


class ActuatorAction(BaseModel):
    """Actions executed or requested by the deterministic PolicyAgent."""

    model_config = ConfigDict(frozen=True)

    account_locked: bool = Field(default=False, description="Core banking account lockout status")
    tx_blocked: bool = Field(default=False, description="Transaction blocked status")
    alert_dispatched: bool = Field(default=False, description="Customer alert dispatched")
    dispatch_channel: str = Field(default="LOG_ONLY", description="Channel used for security alert")
    early_containment: bool = Field(
        default=False,
        description="True if lockout occurred before orchestrator verdict via early containment",
    )


class CaseNarrative(BaseModel):
    """Asynchronous deep review narrative generated by Gemini Pro."""

    model_config = ConfigDict(frozen=True)

    executive_summary: str = Field(description="High-level narrative of the fraud event")
    chronology: list[str] = Field(default_factory=list, description="Reconstructed event timeline")
    recommended_action: str = Field(description="Analyst recommendation")
    confidence_score: float = Field(ge=0.0, le=1.0, description="Agent confidence in review")


class AnalystDecision(BaseModel):
    """Manual review decision recorded by a human fraud analyst."""

    model_config = ConfigDict(frozen=True)

    action: str = Field(description="APPROVE | CONFIRM_FRAUD | UNLOCK")
    reason: str = Field(description="Analyst rationale")
    analyst_uid: str = Field(description="Analyst user identifier")
    at: int = Field(description="Timestamp of action in epoch milliseconds")


class ModelVersions(BaseModel):
    """Version tracking of active prompts and risk policies."""

    model_config = ConfigDict(frozen=True)

    policy: str = Field(default="1.0.0", description="risk_policy.yaml semantic version")
    orchestrator: dict[str, str] = Field(
        default_factory=dict, description="Orchestrator model & prompt version"
    )
    specialist: dict[str, str] = Field(
        default_factory=dict, description="Specialist model & prompt version"
    )


class LatencyBreakdown(BaseModel):
    """Millisecond latency metrics across pipeline stages."""

    model_config = ConfigDict(frozen=True)

    total: int = Field(default=0, description="Total pipeline latency in ms")
    enrichment: int = Field(default=0, description="Deterministic enrichment latency in ms")
    specialists: int = Field(default=0, description="Parallel specialists latency in ms")
    orchestrator: int = Field(default=0, description="Orchestrator synthesis latency in ms")
    policy: int = Field(default=0, description="Policy execution and actuation latency in ms")


class Verdict(BaseModel):
    """Final, explainable investigation verdict and risk assessment."""

    model_config = ConfigDict(frozen=True)

    tx_id: str = Field(description="Transaction identifier")
    user_id: str = Field(description="Customer identifier")
    status: InvestigationStatus = Field(
        default=InvestigationStatus.COMPLETED,
        description="Investigation lifecycle state",
    )
    threat_score: int = Field(ge=0, le=100, description="Final 0-100 composite threat score")
    risk_level: RiskLevel = Field(description="Categorical risk band")
    decision: Decision = Field(description="Automated policy decision")
    should_actuate: bool = Field(
        default=False, description="True if automated containment was required"
    )
    typology: Typology = Field(default=Typology.NONE, description="Classified fraud pattern")
    rationale: str = Field(description="Evidence-backed human readable explanation")
    cited_evidence: list[str] = Field(
        default_factory=list,
        description="Pointers to validated signals used in decision",
    )
    score_breakdown: ScoreBreakdown | None = Field(
        default=None, description="Detailed score decomposition"
    )
    actuator_action: ActuatorAction | None = Field(
        default=None, description="Actions executed by actuator"
    )
    features_snapshot: dict[str, Any] | None = Field(
        default=None, description="Sanitized feature snapshot"
    )
    deep_review: CaseNarrative | None = Field(default=None, description="Asynchronous deep review")
    analyst_decision: AnalystDecision | None = Field(
        default=None, description="Human analyst override"
    )
    degraded: bool = Field(
        default=False, description="True if fallback path was used due to model failure"
    )
    versions: ModelVersions | None = Field(
        default=None, description="Model and policy version metadata"
    )
    latency_ms: LatencyBreakdown = Field(
        default_factory=LatencyBreakdown, description="Latency breakdown"
    )
    started_at: int | None = Field(default=None, description="Pipeline start timestamp (epoch ms)")
    completed_at: int | None = Field(
        default=None, description="Pipeline completion timestamp (epoch ms)"
    )
    event_count: int = Field(default=0, description="Total telemetry events generated")
